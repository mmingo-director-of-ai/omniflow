#!/usr/bin/env python3
"""Writes the `omniflow.waveform` custom SF Symbol into Symbols.xcassets.

The bars come from `OmniWaveform` (Sources/Core/FreeFlow/WaveformGlyph.swift):
the rest heights are parsed from that file, so the symbol and the in-app glyph
stay one shape. Three masters (Ultralight, Regular, Black) differ only in bar
width; every master uses the same path commands, so the symbol interpolates
across all nine weights and scales. Re-run after changing the Swift shape.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SWIFT = ROOT / "OmniFlow/Sources/Core/FreeFlow/WaveformGlyph.swift"
OUT = ROOT / "OmniFlow/Symbols.xcassets/omniflow.waveform.symbolset"

source = SWIFT.read_text()
HEIGHTS = [float(v) for v in re.search(r"restHeights: \[CGFloat\] = \[([^\]]+)\]", source).group(1).split(",")]
REGULAR_BAR = float(re.search(r"barWidth: CGFloat = ([0-9.]+)", source).group(1))

# Template geometry (SF Symbols template v3, small scale): the baseline is
# y=696 and the cap height is 70.459. The glyph is centred on the cap-height
# midline and slightly taller than caps, as Apple's own waveform glyphs are.
BASELINE, CAP = 696.0, 70.459
SIDE = 84.0          # glyph width and full bar height, in template units
BEARING = 5.0        # side bearing on each side
MID = -CAP / 2       # vertical centre, relative to the baseline
KAPPA = 0.5523       # cubic approximation of a quarter circle
MASTERS = {          # weight -> (column x on the artboard, bar width fraction)
    "Ultralight-S": (560.0, REGULAR_BAR * 0.55),
    "Regular-S": (1450.0, REGULAR_BAR),
    "Black-S": (2350.0, REGULAR_BAR * 1.5),
}


def capsule(x, top, width, height):
    """A vertical capsule as a fixed command sequence (M, C, C, L, C, C, Z)."""
    r = width / 2
    k = r * KAPPA
    x0, x1, bottom = x, x + width, top + height
    f = lambda v: f"{v:.3f}".rstrip("0").rstrip(".")
    return (
        f"M{f(x0)} {f(top + r)}"
        f"C{f(x0)} {f(top + r - k)} {f(x0 + r - k)} {f(top)} {f(x0 + r)} {f(top)}"
        f"C{f(x0 + r + k)} {f(top)} {f(x1)} {f(top + r - k)} {f(x1)} {f(top + r)}"
        f"L{f(x1)} {f(bottom - r)}"
        f"C{f(x1)} {f(bottom - r + k)} {f(x0 + r + k)} {f(bottom)} {f(x0 + r)} {f(bottom)}"
        f"C{f(x0 + r - k)} {f(bottom)} {f(x0)} {f(bottom - r + k)} {f(x0)} {f(bottom - r)}"
        "Z"
    )


def glyph(bar_fraction):
    width = SIDE * bar_fraction
    gap = (SIDE - width * len(HEIGHTS)) / (len(HEIGHTS) - 1)
    parts = []
    for index, fraction in enumerate(HEIGHTS):
        height = max(width, SIDE * fraction)
        parts.append(capsule(BEARING + index * (width + gap), MID - height / 2, width, height))
    return "".join(parts)


guide = 'style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;"'
margin = 'style="fill:none;stroke:#00AEEF;stroke-width:0.5;opacity:1.0;"'
lines = [
    f'<line id="Baseline-S" {guide} x1="263" x2="3036" y1="696" y2="696"/>',
    f'<line id="Capline-S" {guide} x1="263" x2="3036" y1="625.541" y2="625.541"/>',
    f'<line id="Baseline-M" {guide} x1="263" x2="3036" y1="1126" y2="1126"/>',
    f'<line id="Capline-M" {guide} x1="263" x2="3036" y1="1055.54" y2="1055.54"/>',
    f'<line id="Baseline-L" {guide} x1="263" x2="3036" y1="1556" y2="1556"/>',
    f'<line id="Capline-L" {guide} x1="263" x2="3036" y1="1485.54" y2="1485.54"/>',
]
symbols = []
for name, (column, bar) in MASTERS.items():
    lines.append(f'<line id="left-margin-{name}" {margin} x1="{column:g}" x2="{column:g}" y1="600.785" y2="720.121"/>')
    right = column + SIDE + 2 * BEARING
    lines.append(f'<line id="right-margin-{name}" {margin} x1="{right:g}" x2="{right:g}" y1="600.785" y2="720.121"/>')
    symbols.append(f'<g id="{name}" transform="matrix(1 0 0 1 {column:g} {BASELINE:g})"><path class="monochrome-0 multicolor-0:tintColor hierarchical-0:primary SFSymbolsPreviewWireframe" d="{glyph(bar)}"/></g>')

svg = f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">
<!-- Generated by scripts/render-waveform-symbol.py from OmniWaveform; do not edit by hand. -->
<svg version="1.1" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="3300" height="2200">
<style>.monochrome-0 {{-sf-multicolor:none;}} .multicolor-0:tintColor {{fill:#007AFF;opacity:1.0}} .hierarchical-0:primary {{-sf-hierarchical-layer:primary}} .SFSymbolsPreviewWireframe {{fill:none;opacity:1.0;stroke:black;stroke-width:0.5}}</style>
<g id="Notes">
<rect height="2200" id="artboard" style="fill:white;opacity:1" width="3300" x="0" y="0"/>
<text style="stroke:none;fill:black;font-family:sans-serif;font-size:13;font-weight:bold;" transform="matrix(1 0 0 1 263 322)">Weight/Scale Variations</text>
<text id="template-version" style="stroke:none;fill:black;font-family:sans-serif;font-size:13;" transform="matrix(1 0 0 1 2952.0 1933)">Template v.3.0</text>
</g>
<g id="Guides">
{chr(10).join(lines)}
</g>
<g id="Symbols">
{chr(10).join(symbols)}
</g>
</svg>
"""

OUT.mkdir(parents=True, exist_ok=True)
(OUT / "omniflow.waveform.svg").write_text(svg)
(OUT / "Contents.json").write_text(json.dumps({
    "info": {"author": "xcode", "version": 1},
    "symbols": [{"filename": "omniflow.waveform.svg", "idiom": "universal"}],
}, indent=2) + "\n")
print(f"wrote {OUT.relative_to(ROOT)} ({len(HEIGHTS)} bars, 3 masters)")
