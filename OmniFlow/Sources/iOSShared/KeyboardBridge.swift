import Foundation

/// The contract between the OmniFlow app and the OmniFlow keyboard.
///
/// iOS keyboards can't use the microphone, so the app records: the keyboard
/// opens OmniFlow once to start a keyboard session, the user returns to the
/// app they were typing in, and from then on the keyboard's mic button asks
/// the app (still running in the background with the microphone open) to
/// listen, then inserts the text the app returns.
///
/// Transport (free development team: no App Group). For each session the
/// keyboard picks a fresh 256-bit token and a random high port and passes
/// both once, in the URL that opens OmniFlow. The app binds an HTTP listener
/// to 127.0.0.1 on that port only, requires the token on every request
/// (constant-time compare), rate-limits, and closes the listener when the
/// session ends; the token dies with it. State changes are announced as a
/// payload-free Darwin notification, which carries no data. The token is
/// never logged or stored by the app. Another app on the device could find
/// the port; the token is what keeps it out.
///
/// Initiation: any app can open the pairing URL with a token it chose. The
/// app therefore starts a session without asking only when iOS reports the
/// URL came from this keyboard or this app (`sourceApplication` is revealed
/// only within the same team); from any other or unknown source it asks the
/// user first and opens no listener until they allow it. A session serves
/// only its own live text and its last result (cleared once inserted), never
/// history. A new allowed pairing replaces the old one. Switch to an App
/// Group container once a paid team is available.
///
/// Staying reachable: during a session the app holds an active
/// `playAndRecord` audio session with the microphone running (Info.plist
/// `UIBackgroundModes: audio`), which keeps the process running in the
/// background; the system microphone indicator stays on. If iOS suspends or
/// ends the app anyway, requests fail, the keyboard treats the session as
/// over, and its mic button opens OmniFlow to pair again. Nothing is queued.
enum KeyboardBridge {
    static let host = "127.0.0.1"
    static let portRange: ClosedRange<UInt16> = 49_152...65_000
    static let scheme = "omniflow"
    static let sessionHost = "keyboard-session"
    static let tokenHeader = "X-OmniFlow-Pairing"
    static let stateChanged = "com.mengohlabs.omniflow.keyboard.state"

    /// One session's credentials, generated by the keyboard.
    struct Pairing: Codable, Equatable, Sendable {
        let token: String
        let port: UInt16
        /// The app the user was typing in, so OmniFlow can hand straight back to it.
        var hostBundleID: String?

        static func make(host: String? = nil) -> Pairing {
            Pairing(token: makeToken(), port: .random(in: portRange), hostBundleID: host.flatMap { isValidBundleID($0) ? $0 : nil })
        }

        var isValid: Bool {
            KeyboardBridge.isValidToken(token) && portRange.contains(port) && (hostBundleID.map { Self.isValidBundleID($0) } ?? true)
        }

        static func isValidBundleID(_ id: String) -> Bool {
            (3...155).contains(id.count) && id.contains(".")
                && id.allSatisfy { $0.isASCII && ($0.isLetter || $0.isNumber || $0 == "." || $0 == "-") }
        }

        var url: URL {
            var components = URLComponents()
            components.scheme = scheme; components.host = sessionHost
            components.queryItems = [URLQueryItem(name: "token", value: token), URLQueryItem(name: "port", value: String(port))]
                + (hostBundleID.map { [URLQueryItem(name: "host", value: $0)] } ?? [])
            return components.url!
        }

        init(token: String, port: UInt16, hostBundleID: String? = nil) {
            self.token = token; self.port = port; self.hostBundleID = hostBundleID
        }

        /// Parses the URL the keyboard opened; nil for anything malformed.
        init?(url: URL) {
            guard url.scheme == scheme, url.host == sessionHost,
                  let items = URLComponents(url: url, resolvingAgainstBaseURL: false)?.queryItems, (2...3).contains(items.count),
                  Set(items.map(\.name)).isSubset(of: ["token", "port", "host"]), Set(items.map(\.name)).count == items.count,
                  let token = items.first(where: { $0.name == "token" })?.value,
                  let port = items.first(where: { $0.name == "port" })?.value.flatMap(UInt16.init) else { return nil }
            self.init(token: token, port: port, hostBundleID: items.first(where: { $0.name == "host" })?.value)
            guard isValid else { return nil }
        }
    }

    /// Accepts only well-formed tokens: 43 base64url characters (32 random bytes).
    static func isValidToken(_ token: String) -> Bool {
        token.count == 43 && token.allSatisfy { $0.isASCII && ($0.isLetter || $0.isNumber || $0 == "-" || $0 == "_") }
    }

    static func makeToken() -> String {
        var bytes = [UInt8](repeating: 0, count: 32)
        for index in bytes.indices { bytes[index] = UInt8.random(in: .min ... .max) }
        return Data(bytes).base64EncodedString()
            .replacingOccurrences(of: "+", with: "-").replacingOccurrences(of: "/", with: "_")
            .replacingOccurrences(of: "=", with: "")
    }

    static let keyboardBundleID = "com.mengohlabs.NotchLee.ios.keyboard"
    static let appBundleID = "com.mengohlabs.NotchLee.ios"

    /// Whether a pairing URL may start a session without asking the user.
    enum PairingDecision: Equatable { case start, confirm }

    static func decide(sourceApplication: String?) -> PairingDecision {
        guard let sourceApplication else { return .confirm }
        return sourceApplication == keyboardBundleID || sourceApplication == appBundleID ? .start : .confirm
    }

    enum Command: String { case state, start, stop, cancel, consume }

    struct State: Codable, Equatable, Sendable {
        enum Phase: String, Codable, Sendable { case off, ready, listening, finishing }
        var phase: Phase = .off
        /// The session turns itself off at this time unless used again.
        var expires: Date?
        var liveText = ""
        /// Set once per dictation; the keyboard inserts it, then sends `consume`.
        var result: Result?
        var message: String?
        /// While listening: the live voice bands (0...1) and level, so the keyboard
        /// can draw the same voice ring as the app. The keyboard polls for these.
        var bands: [Float] = []
        var level: Float = 0

        struct Result: Codable, Equatable, Sendable {
            let id: UUID
            let text: String
        }
    }

    static func post() {
        CFNotificationCenterPostNotification(CFNotificationCenterGetDarwinNotifyCenter(),
                                             CFNotificationName(stateChanged as CFString), nil, nil, true)
    }

    /// Calls `handler` on the main queue whenever the app posts a state change.
    static func observe(handler: @escaping @MainActor () -> Void) -> Observation { Observation(handler: handler) }

    /// The handler only ever runs on the main queue.
    final class Observation: @unchecked Sendable {
        private let handler: @MainActor () -> Void

        fileprivate init(handler: @escaping @MainActor () -> Void) {
            self.handler = handler
            CFNotificationCenterAddObserver(CFNotificationCenterGetDarwinNotifyCenter(), Unmanaged.passUnretained(self).toOpaque(), { _, observer, _, _, _ in
                guard let observer else { return }
                let me = Unmanaged<Observation>.fromOpaque(observer).takeUnretainedValue()
                DispatchQueue.main.async { MainActor.assumeIsolated { me.handler() } }
            }, KeyboardBridge.stateChanged as CFString, nil, .deliverImmediately)
        }

        deinit {
            CFNotificationCenterRemoveObserver(CFNotificationCenterGetDarwinNotifyCenter(), Unmanaged.passUnretained(self).toOpaque(),
                                               CFNotificationName(KeyboardBridge.stateChanged as CFString), nil)
        }
    }
}
