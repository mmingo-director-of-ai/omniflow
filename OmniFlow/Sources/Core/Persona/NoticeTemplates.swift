import Foundation

/// Tier 1 template pools. Slots: `{percent}`, `{agent}`, `{tool}`, `{mic}`, `{language}` are
/// facts from the event; `{you}` is one of the persona's address terms. A template is eligible
/// only when every fact the event carries appears in it and every slot it uses can be filled.
/// Critical kinds hold flavor lines only; the event's core sentence is appended verbatim.
/// A style without a pool for a kind falls back to the standard pool.
enum NoticeTemplates {
    static func pool(_ style: PersonaStyle, _ kind: NoticeKind) -> [String] {
        if let lines = pools[style]?[kind], !lines.isEmpty { return lines }
        return pools[.standard]?[kind] ?? []
    }

    static let pools: [PersonaStyle: [NoticeKind: [String]]] = [
        .standard: standard, .friendly: friendly, .terse: terse,
        .sarcastic: sarcastic, .drillSergeant: drillSergeant, .abliterated: abliterated,
    ]

